export const APP_WEEKDAYS = {
  ru: ['Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб', 'Вс'],
  en: ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'],
} as const;

export type AppMessageKey = keyof typeof APP_MESSAGES.ru;
export function appMessage(language: 'ru' | 'en', key: AppMessageKey, values: Record<string, string | number> = {}) {
  return APP_MESSAGES[language][key].replace(/\{(\w+)\}/g, (_match: string, name: string) => String(values[name] ?? ''));
}
